    public void EveryVersionAndLevel_MatchesNayuki(int version, QrErrorCorrection level, int expectedMask, string expectedDigest)
    {
        string text = "V" + version.ToString(CultureInfo.InvariantCulture) + ":aB";
        QrCode code = QrCode.Encode(text, level, new QrEncoderOptions { Version = version });

        Assert.Equal(version, code.Version);
        Assert.Equal(expectedMask, code.Mask);
        Assert.Equal((4 * version) + 17, code.Size);

        bool[,] matrix = code.Matrix;
        StringBuilder builder = new();
        for (int r = 0; r < code.Size; r++)
        {
            for (int c = 0; c < code.Size; c++)
            {
                builder.Append(matrix[r, c] ? '1' : '0');
            }
        }

        string digest = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(builder.ToString()))).ToLowerInvariant();
        Assert.Equal(expectedDigest, digest);
    }
