    [Fact]
    public void HelloWorld5Q_MatchesReferenceEncoder()
    {
        QrCode code = QrCode.Encode("HELLO WORLD", QrErrorCorrection.Q,
            new QrEncoderOptions { Version = 5, Mask = 0 });

        Assert.Equal(5, code.Version);
        Assert.Equal(0, code.Mask);
        Assert.Equal(37, code.Size);
        bool[,] matrix = code.Matrix;
        for (int row = 0; row < 37; row++)
        {
            string actual = new(Enumerable.Range(0, 37).Select(col => matrix[row, col] ? '1' : '0').ToArray());
            Assert.Equal(HelloWorld5QMatrix[row], actual);
        }
    }

